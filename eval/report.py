"""Generate eval/REPORT.md from the CSVs in eval/results/. Every number comes from those files.

    python -m eval.report
"""

from __future__ import annotations

import csv
import json
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

from healthrag.config import PROJECT_ROOT, Settings, get_settings
from healthrag.evaluation.stats import bootstrap_ci, mean, paired_difference, verdict

REPORT = PROJECT_ROOT / "eval" / "REPORT.md"
NAN = float("nan")


def read_csv(path: Path) -> list[dict]:
    """Rows of a CSV, or [] if it doesn't exist."""
    if not path.exists():
        return []
    with path.open(encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def num(value: str) -> float:
    """CSV cell to float (blank -> NaN)."""
    return float(value) if value not in ("", None) else NAN


def per_item(rows: list[dict], metric: str) -> dict[str, float]:
    """Per-item values of a judge-free metric, keyed by golden id."""
    out: dict[str, float] = {}
    for r in rows:
        answerable = r["answerable"] == "True"
        has_support = r["support_coverage"] != ""
        if metric == "hit" and answerable and has_support:
            out[r["id"]] = 1.0 if r["hit_rank"] else 0.0
        elif metric == "rr" and answerable and has_support:
            out[r["id"]] = 1.0 / int(r["hit_rank"]) if r["hit_rank"] else 0.0
        elif metric == "coverage" and answerable and has_support:
            out[r["id"]] = num(r["support_coverage"])
        elif metric == "match" and answerable:
            out[r["id"]] = 1.0 if r["answer_match"] == "True" else 0.0
        elif metric == "refusal" and not answerable:
            out[r["id"]] = 1.0 if r["refused"] == "True" else 0.0
        elif metric == "false_refusal" and answerable:
            out[r["id"]] = 1.0 if r["refused"] == "True" else 0.0
        elif metric == "cost":
            out[r["id"]] = num(r["est_cost_usd"])
        elif metric == "latency":
            out[r["id"]] = num(r["latency_ms"])
    return out


def ragas_item(rows: list[dict], metric: str) -> dict[str, float]:
    """Per-item RAGAS scores (errors and refusals without statements stay NaN)."""
    return {r["id"]: num(r[metric]) for r in rows if not r["error"]}


def fmt(value: float, digits: int = 3) -> str:
    """Number for a table, or a dash for NaN."""
    return "–" if value != value else f"{value:.{digits}f}"


def ci_cell(values: list[float], settings: Settings) -> str:
    """'mean (low–high)' for a list of per-item values."""
    e = settings.evaluation
    low, high = bootstrap_ci(values, e.bootstrap_samples, e.seed)
    return f"{fmt(mean(values))} ({fmt(low)}–{fmt(high)})"


def compare(name_a: str, name_b: str, a: dict[str, float], b: dict[str, float], label: str, settings: Settings,
            higher_is_better: bool = True) -> str:  # fmt: skip
    """One row of a paired comparison table."""
    e = settings.evaluation
    ids = sorted(set(a) & set(b))
    diff, low, high, n = paired_difference([a[i] for i in ids], [b[i] for i in ids], e.bootstrap_samples, e.seed)
    return (f"| {label} | `{name_a}` − `{name_b}` | {fmt(diff)} | {fmt(low)} to {fmt(high)} | {n} | "
            f"{verdict(low, high, name_a, name_b, higher_is_better)} |")  # fmt: skip


def build(settings: Settings) -> str:
    """Render the full report."""
    results = settings.evaluation.results_dir
    configs = list(settings.evaluation.configs)
    runs = {name: read_csv(results / f"{name}.csv") for name in configs}
    ragas = {name: read_csv(results / f"{name}_ragas.csv") for name in configs}
    repeat = {name: read_csv(results / f"{name}_ragas_repeat.csv") for name in configs}
    golden = [json.loads(line) for line in settings.evaluation.golden_file.read_text(encoding="utf-8").splitlines()]
    subsets = json.loads(settings.evaluation.subsets_file.read_text(encoding="utf-8"))
    subset, comparison = subsets["ragas"], subsets["comparison"]
    llm = settings.llm
    n_answerable = sum(1 for g in golden if g["type"] != "unanswerable")

    lines = [
        "# Evaluation report",
        "",
        f"Generated by `python -m eval.report` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} from the CSVs in "
        "`eval/results/`. Every number below is computed from those files.",
        "",
        "## Setup",
        "",
        f"- Golden set: `eval/golden.jsonl`, n = {len(golden)} ({n_answerable} answerable, "
        f"{len(golden) - n_answerable} unanswerable). All items are still `\"status\": \"draft\"` (not yet reviewed "
        "by hand).",
        f"- Models: small `{llm.small_model}`, large `{llm.large_model}` (both on Groq); RAGAS judge "
        f"`{llm.judge_model}`, a different model family from the large model.",
        f"- Retrieval: `{settings.retrieval.embedding_model}` + BM25, RRF k = {settings.retrieval.rrf_k}, "
        f"re-ranker `{settings.retrieval.rerank_model}`, top-{settings.retrieval.final_k}.",
        "- Guardrails are off during these runs (they are evaluated separately in `reports/guardrails_report.md`).",
        f"- Intervals are 95% bootstrap intervals ({settings.evaluation.bootstrap_samples} resamples). Comparisons use "
        "paired bootstrap intervals on per-item differences; an interval that contains 0 is reported as "
        "\"no clear difference\".",
        "- Costs are estimates at the reference prices in `config.yaml`; actual cost on the free tier was $0.",
        "",
        "## Configurations",
        "",
        "| Config | Retrieval | Generator | Items |",
        "|---|---|---|---|",
    ]
    for name, c in settings.evaluation.configs.items():
        items_label = f"all {len(golden)}" if c.items == "all" else f"comparison subset ({len(comparison)})"
        lines.append(f"| `{name}` | {c.retrieval_mode} | {c.generator} | {items_label} |")
    lines += [
        "",
        f"The comparison subset (`eval/subsets.json`) is a fixed, stratified {len(comparison)}-item sample that "
        f"contains the {len(subset)}-item RAGAS subset. Groq's free tier allows about 200K tokens per model per "
        "day, which isn't enough to run all five configs on every item in one day. Paired comparisons below use "
        "the items both configs answered.",
    ]

    lines += [
        "",
        "## Judge-free metrics (all golden items)",
        "",
        "Hit@5 and MRR@5: rank of the first retrieved chunk that carries a golden support (source + supporting "
        "text). Answer match: the answer contains the expected facts. Refusal accuracy: unanswerable items "
        "answered with \"not in the documents\". False refusals: answerable items refused.",
        "",
        "| Config | n | Hit@5 | MRR@5 | Support coverage | Answer match | Refusal accuracy | False refusals | "
        "Median latency (ms) | Est. cost / query (USD) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name in configs:
        rows = runs[name]
        if not rows:
            lines.append(f"| `{name}` | 0 | not run | | | | | | | |")
            continue
        m = {k: list(per_item(rows, k).values()) for k in ("hit", "rr", "coverage", "match", "refusal",
                                                            "false_refusal", "cost", "latency")}  # fmt: skip
        lines.append(
            f"| `{name}` | {len(rows)} | {ci_cell(m['hit'], settings)} | {ci_cell(m['rr'], settings)} | {fmt(mean(m['coverage']))} | "
            f"{ci_cell(m['match'], settings)} | {fmt(mean(m['refusal']))} ({int(sum(m['refusal']))}/{len(m['refusal'])}) | "
            f"{fmt(mean(m['false_refusal']))} ({int(sum(m['false_refusal']))}/{len(m['false_refusal'])}) | "
            f"{statistics.median(m['latency']):.0f} | {mean(m['cost']):.6f} |"
        )

    main = "rerank_tiered"
    if runs.get(main):
        lines += ["", f"### Answer match by question type (`{main}`)", "", "| Type | Answer match | n |", "|---|---|---|"]
        types = sorted({r["type"] for r in runs[main] if r["answerable"] == "True"})
        for t in types:
            vals = [1.0 if r["answer_match"] == "True" else 0.0 for r in runs[main] if r["type"] == t]
            lines.append(f"| {t} | {fmt(mean(vals))} | {len(vals)} |")
        routes = [r["route"] for r in runs[main]]
        lines.append("")
        lines.append(f"Tiered routing sent {routes.count('large')} of {len(routes)} questions to the large model.")

    lines += [
        "",
        "## RAGAS (fixed subset)",
        "",
        f"Faithfulness and answer relevancy on the fixed, stratified subset in `eval/ragas_subset.json` "
        f"(n = {len(subset)} answerable items). The free judge tier allows about 200K tokens a day, so the "
        "full set is not judged; context quality is covered by the judge-free metrics above.",
        "",
        "| Config | Faithfulness | Answer relevancy | Items scored |",
        "|---|---|---|---|",
    ]
    for name in configs:
        rows = ragas[name]
        if not rows:
            lines.append(f"| `{name}` | not run | not run | 0 / {len(subset)} |")
            continue
        f = list(ragas_item(rows, "faithfulness").values())
        r = list(ragas_item(rows, "answer_relevancy").values())
        scored = sum(1 for row in rows if not row["error"])
        lines.append(f"| `{name}` | {ci_cell(f, settings)} | {ci_cell(r, settings)} | {scored} / {len(subset)} |")

    lines += ["", "## Comparisons", "", "| Metric | Difference | Mean | 95% CI | n | Reading |", "|---|---|---|---|---|---|"]
    retrieval_pairs = [("hybrid_tiered", "dense_tiered"), ("rerank_tiered", "hybrid_tiered"), ("rerank_tiered", "dense_tiered")]
    generator_pairs = [("rerank_large", "rerank_small"), ("rerank_tiered", "rerank_small"), ("rerank_tiered", "rerank_large")]
    for a, b in retrieval_pairs:
        if runs[a] and runs[b]:
            lines.append(compare(a, b, per_item(runs[a], "hit"), per_item(runs[b], "hit"), "Hit@5", settings))
            lines.append(compare(a, b, per_item(runs[a], "rr"), per_item(runs[b], "rr"), "MRR@5", settings))
            lines.append(compare(a, b, per_item(runs[a], "match"), per_item(runs[b], "match"), "Answer match", settings))
    for a, b in generator_pairs:
        if runs[a] and runs[b]:
            lines.append(compare(a, b, per_item(runs[a], "match"), per_item(runs[b], "match"), "Answer match", settings))
            lines.append(compare(a, b, per_item(runs[a], "refusal"), per_item(runs[b], "refusal"), "Refusal accuracy", settings))
            lines.append(compare(a, b, per_item(runs[a], "cost"), per_item(runs[b], "cost"), "Est. cost / query",
                                 settings, higher_is_better=False))  # fmt: skip
    for a, b in retrieval_pairs + generator_pairs:
        if ragas[a] and ragas[b]:
            lines.append(compare(a, b, ragas_item(ragas[a], "faithfulness"), ragas_item(ragas[b], "faithfulness"),
                                 "Faithfulness", settings))  # fmt: skip

    lines += ["", "## Judge noise", ""]
    noise_rows = [(n, ragas[n], repeat[n]) for n in configs if repeat[n] and ragas[n]]
    if not noise_rows:
        lines.append("Not measured yet: run `python -m eval.ragas_run --config rerank_tiered --repeat`.")
    for name, first, second in noise_rows:
        a, b = ragas_item(first, "faithfulness"), ragas_item(second, "faithfulness")
        ids = sorted(set(a) & set(b))
        diffs = [abs(a[i] - b[i]) for i in ids if a[i] == a[i] and b[i] == b[i]]
        lines.append(
            f"`{name}` judged twice (second run uncached), n = {len(diffs)}: mean absolute faithfulness difference "
            f"{fmt(mean(diffs))}, max {fmt(max(diffs) if diffs else NAN)}; mean faithfulness {fmt(mean(list(a.values())))} "
            f"vs {fmt(mean(list(b.values())))}. The regression threshold in `eval/results/baseline.json` is set above this."
        )
    lines += [
        "",
        "## Limitations",
        "",
        "- The golden set is small and still `draft`; patient items were generated from the CSVs, guideline items were "
        "written by hand against the recommendation statements. Small differences are within noise.",
        "- RAGAS covers a 20-item subset only, because of the free judge quota.",
        "- Answer match is a strict substring check (dates accept common formats); a correct answer phrased "
        "differently can still miss.",
        "- Only dates of birth are redacted; HIPAA Safe Harbor would also require generalising other dates.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    """Write eval/REPORT.md."""
    settings = get_settings()
    REPORT.write_text(build(settings), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
