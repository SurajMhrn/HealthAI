"""Compare the three routers on the router test split.

Run with ``python -m scripts.compare_routers`` (or ``make compare-routers``) after
``make train-router``. Writes ``reports/router_comparison.md`` and
``eval/results/router_predictions.csv``.

Metrics: accuracy (with a 95% bootstrap CI), precision/recall/F1 for "complex",
latency per query, and estimated cost per query at the configured reference prices.
"""

from __future__ import annotations

import csv
import logging
import random
import statistics
import sys
from datetime import datetime, timezone

from sklearn.metrics import accuracy_score, precision_recall_fscore_support

from healthrag.config import PROJECT_ROOT, get_settings
from healthrag.generate.llm import LlmClient, estimated_cost
from healthrag.generate.router import COMPLEX, make_router
from healthrag.retrieve.dense import SentenceTransformerEmbedder
from scripts.train_router import load_split

log = logging.getLogger("compare_routers")

REPORT = PROJECT_ROOT / "reports" / "router_comparison.md"
PREDICTIONS = PROJECT_ROOT / "eval" / "results" / "router_predictions.csv"
BOOTSTRAP_SAMPLES = 2000


def bootstrap_accuracy_ci(correct: list[bool], seed: int) -> tuple[float, float]:
    """95% percentile bootstrap interval for accuracy."""
    rng = random.Random(seed)
    n = len(correct)
    stats = sorted(sum(correct[rng.randrange(n)] for _ in range(n)) / n for _ in range(BOOTSTRAP_SAMPLES))
    return stats[int(0.025 * BOOTSTRAP_SAMPLES)], stats[int(0.975 * BOOTSTRAP_SAMPLES) - 1]


def metrics(gold: list[str], pred: list[str]) -> dict[str, float]:
    """Accuracy and precision/recall/F1 for the "complex" class."""
    p, r, f, _ = precision_recall_fscore_support(gold, pred, pos_label=COMPLEX, average="binary", zero_division=0)
    return {"accuracy": accuracy_score(gold, pred), "precision": p, "recall": r, "f1": f}


def main() -> int:
    """Route every test item with each router and write the comparison."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    settings = get_settings()
    r = settings.retrieval
    test = load_split(settings.router.labels_file, "test")
    embedder = SentenceTransformerEmbedder(
        r.embedding_model, r.embedding_revision, r.query_instruction, r.embed_batch_size, r.max_seq_length
    )
    client = LlmClient(settings)
    embedder.encode(["warm up"])  # first call loads weights; keep it out of the latency numbers

    rows: list[dict] = []
    for name in ("rules", "rules_llm", "trained"):
        router = make_router(name, settings, client, embedder)
        for item in test:
            decision = router.route(item["query"])
            rows.append(
                {
                    "router": name,
                    "query": item["query"],
                    "source": item["source"],
                    "gold": item["label"],
                    "pred": decision.label,
                    "reason": decision.reason,
                    "latency_ms": round(decision.latency_ms, 2),
                    "tokens_in": decision.tokens_in,
                    "tokens_out": decision.tokens_out,
                    "est_cost_usd": estimated_cost(settings, decision.model or "", decision.tokens_in, decision.tokens_out),
                }
            )
        log.info("%s done", name)

    PREDICTIONS.parent.mkdir(parents=True, exist_ok=True)
    with PREDICTIONS.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    REPORT.write_text(render(rows, settings, len(test)), encoding="utf-8", newline="\n")
    log.info("Wrote %s and %s", REPORT, PREDICTIONS)
    return 0


def render(rows: list[dict], settings, n: int) -> str:  # noqa: ANN001
    """Markdown tables computed from the prediction rows."""
    small = settings.llm.small_model
    lines = [
        "# Router comparison",
        "",
        f"Generated by `python -m scripts.compare_routers` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} "
        f"from `eval/results/router_predictions.csv`.",
        "",
        f"Test split of `eval/router_labels.jsonl`: n = {n} (held-out templates + hand-written paraphrases; "
        "labels come from how each question was built, all still `draft`). Positive class: `complex`. "
        f"The LLM router uses `{small}`; the trained router is logistic regression on "
        f"`{settings.retrieval.embedding_model}` embeddings. Latency is per query on this laptop's CPU (the LLM "
        "router's figure is the measured API call). Cost is estimated at the reference prices in `config.yaml`; "
        "actual cost on the free tier is $0.",
        "",
        "| Router | Accuracy | 95% CI | Precision | Recall | F1 | Median latency (ms) | p95 latency (ms) | Est. cost / query (USD) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    seed = settings.router.seed
    for name in ("rules", "rules_llm", "trained"):
        part = [r for r in rows if r["router"] == name]
        m = metrics([r["gold"] for r in part], [r["pred"] for r in part])
        low, high = bootstrap_accuracy_ci([r["gold"] == r["pred"] for r in part], seed)
        lat = sorted(r["latency_ms"] for r in part)
        p95 = lat[min(len(lat) - 1, int(0.95 * len(lat)))]
        cost = sum(r["est_cost_usd"] for r in part) / len(part)
        lines.append(
            f"| `{name}` | {m['accuracy']:.3f} | {low:.3f}–{high:.3f} | {m['precision']:.3f} | {m['recall']:.3f} | "
            f"{m['f1']:.3f} | {statistics.median(lat):.1f} | {p95:.1f} | {cost:.7f} |"
        )
    lines += [
        "",
        "## Accuracy by subset",
        "",
        "| Router | Held-out templates | Paraphrases |",
        "|---|---|---|",
    ]
    for name in ("rules", "rules_llm", "trained"):
        cells = []
        for subset in ("template", "paraphrase"):
            part = [r for r in rows if r["router"] == name and r["source"].startswith(subset)]
            correct = sum(r["gold"] == r["pred"] for r in part)
            cells.append(f"{correct}/{len(part)} ({correct / len(part):.3f})")
        lines.append(f"| `{name}` | {cells[0]} | {cells[1]} |")
    lines += ["", "## Errors", ""]
    for name in ("rules", "rules_llm", "trained"):
        errors = [r for r in rows if r["router"] == name and r["gold"] != r["pred"]]
        lines += [f"### `{name}`: {len(errors)} errors", ""]
        if errors:
            lines += ["| Question | Gold | Predicted | Reason |", "|---|---|---|---|"]
            for r in errors:
                q = r["query"].replace("|", "\\|")
                lines.append(f"| {q} | {r['gold']} | {r['pred']} | {r['reason'].replace('|', '/')} |")
            lines.append("")
    lines += [
        "Overlapping confidence intervals mean no clear difference between routers at this n.",
    ]
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    sys.exit(main())
