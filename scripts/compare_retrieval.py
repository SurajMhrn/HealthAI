"""Run the same queries through dense, BM25, hybrid and hybrid + re-rank, side by side.

Run with ``python -m scripts.compare_retrieval`` (or ``make compare``) after ``make index``.
Writes ``reports/retrieval_comparison.md``.

Queries live in ``eval/retrieval_queries.jsonl``. Each has a simple expectation (source
file, section and/or a text substring) written together with the query. A hit is a
top-k chunk that meets every expectation. This is a smoke test with a small n, not the
evaluation: the hand-reviewed golden set comes in Phase 5.
"""

from __future__ import annotations

import json
import logging
import statistics
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from healthrag.config import PROJECT_ROOT, get_settings
from healthrag.retrieve.filters import Filters, matches
from healthrag.retrieve.retriever import MODES, Hit, Retriever

log = logging.getLogger("compare_retrieval")

QUERIES = PROJECT_ROOT / "eval" / "retrieval_queries.jsonl"
REPORT = PROJECT_ROOT / "reports" / "retrieval_comparison.md"
CLINICAL_SECTIONS = ("Conditions", "Medications", "Encounters")


@dataclass
class QueryRun:
    """One query through one mode."""

    hits: list[Hit]
    first_relevant_rank: int | None
    total_ms: float


def pick_patient(records: list[dict], term: str, filters: Filters) -> str:
    """The first patient (by pseudonymous ID) with a clinical chunk that mentions ``term`` and passes ``filters``.

    Deterministic, and guarantees the query has at least one candidate chunk to find.
    """
    term = term.lower()
    candidates = sorted(
        {
            r["patient_id"]
            for r in records
            if r["doc_type"] == "patient_record"
            and r["section"] in CLINICAL_SECTIONS
            and term in r["text"].lower()
            and matches(r, filters)
        }
    )
    if not candidates:
        raise ValueError(f"No patient chunk mentions {term!r}")
    return candidates[0]


def is_relevant(record: dict, expect: dict) -> bool:
    """Whether a chunk meets every expectation of a query."""
    if "source" in expect and expect["source"] not in record["source"]:
        return False
    if "section" in expect and record["section"] != expect["section"]:
        return False
    return not ("text" in expect and expect["text"].lower() not in record["text"].lower())


def _snippet(record: dict, width: int = 90) -> str:
    body = record["text"].split("\n", 1)[-1].replace("\n", " / ").replace("|", "\\|")
    return body[:width] + ("…" if len(body) > width else "")


def main() -> int:
    """Run every query in every mode and write the Markdown comparison."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    settings = get_settings()
    retriever = Retriever.from_settings(settings)
    queries = [json.loads(line) for line in QUERIES.read_text(encoding="utf-8").splitlines() if line.strip()]
    k = settings.retrieval.final_k

    # Warm up both models so the first query's latency isn't inflated by lazy initialisation.
    retriever.search("warm up", mode="hybrid_rerank")

    runs: dict[str, dict[str, QueryRun]] = {}
    filters_used: dict[str, Filters] = {}
    for q in queries:
        base = Filters(doc_type=q.get("doc_type"), date_from=q.get("date_from"), date_to=q.get("date_to"))
        patient = pick_patient(retriever.records, q["patient_with"], base) if "patient_with" in q else None
        filters = Filters(
            doc_type=q.get("doc_type") or ("patient_record" if patient else None),
            patient_id=patient,
            date_from=q.get("date_from"),
            date_to=q.get("date_to"),
        )
        filters_used[q["id"]] = filters
        runs[q["id"]] = {}
        for mode in MODES:
            result = retriever.search(q["query"], filters, mode)
            rank = next((i for i, h in enumerate(result.hits, 1) if is_relevant(h.record, q["expect"])), None)
            runs[q["id"]][mode] = QueryRun(result.hits, rank, result.timings_ms["total"])
        log.info("%s done", q["id"])

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(render(queries, runs, filters_used, settings, k), encoding="utf-8", newline="\n")
    log.info("Wrote %s", REPORT)
    return 0


def render(queries: list[dict], runs: dict, filters_used: dict[str, Filters], settings, k: int) -> str:  # noqa: ANN001
    """Markdown report: summary table, then each query's top results per mode."""
    r = settings.retrieval
    n = len(queries)
    lines = [
        "# Retrieval comparison",
        "",
        f"Generated by `python -m scripts.compare_retrieval` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}. "
        f"n = {n} queries from `eval/retrieval_queries.jsonl`, top-{k}, CPU only.",
        "",
        f"Embedder `{r.embedding_model}`, re-ranker `{r.rerank_model}`, RRF k = {r.rrf_k}, "
        f"{r.candidates_per_retriever} candidates per retriever, re-rank pool {r.rerank_top_n}.",
        "",
        "Each query's expectation (source, section and/or text) was written with the query, so this is a "
        f"smoke test, not an evaluation. With n = {n}, differences of one or two queries are noise.",
        "",
        "| Mode | Hit@" + str(k) + " | MRR@" + str(k) + " | Median latency (ms) | Max latency (ms) |",
        "|---|---|---|---|---|",
    ]
    for mode in MODES:
        mode_runs = [runs[q["id"]][mode] for q in queries]
        hits = sum(1 for run in mode_runs if run.first_relevant_rank)
        mrr = sum(1 / run.first_relevant_rank for run in mode_runs if run.first_relevant_rank) / n
        latencies = [run.total_ms for run in mode_runs]
        lines.append(
            f"| `{mode}` | {hits}/{n} | {mrr:.3f} | {statistics.median(latencies):.0f} | {max(latencies):.0f} |"
        )
    lines += ["", "## Per query", ""]
    for q in queries:
        f = filters_used[q["id"]]
        active = {key: v for key, v in vars(f).items() if v}
        lines += [
            f"### {q['id']}: {q['query']}",
            "",
            f"Filters: `{json.dumps(active)}` · expects `{json.dumps(q['expect'])}`",
            "",
            "| Mode | First relevant rank | Top results (rank. section · snippet) |",
            "|---|---|---|",
        ]
        for mode in MODES:
            run = runs[q["id"]][mode]
            top = "<br>".join(
                f"{i}. {'**' if is_relevant(h.record, q['expect']) else ''}{Path(h.record['source']).stem[:28]} · "
                f"{h.record['section'][:30]}{'**' if is_relevant(h.record, q['expect']) else ''} · {_snippet(h.record)}"
                for i, h in enumerate(run.hits[:3], 1)
            )
            lines.append(f"| `{mode}` | {run.first_relevant_rank or '-'} | {top} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    sys.exit(main())
