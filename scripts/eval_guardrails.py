"""Evaluate the guardrails: input rails on eval/attacks.jsonl, output rail on eval/output_checks.jsonl,
and injection flags on the poisoned fixture and the real corpus.

Run with ``python -m scripts.eval_guardrails`` (or ``make eval-guard``). Writes
``eval/results/guardrail_results.csv`` and ``reports/guardrails_report.md``.
"""

from __future__ import annotations

import csv
import json
import logging
import random
import statistics
import sys
from collections import Counter
from datetime import datetime, timezone

from healthrag.config import PROJECT_ROOT, get_settings
from healthrag.generate.factory import query_redactor
from healthrag.guard.patterns import injection_matches
from healthrag.guard.rails import Guard

log = logging.getLogger("eval_guardrails")

ATTACKS = PROJECT_ROOT / "eval" / "attacks.jsonl"
OUTPUT_CHECKS = PROJECT_ROOT / "eval" / "output_checks.jsonl"
POISONED = PROJECT_ROOT / "tests" / "fixtures" / "poisoned_chunks.jsonl"
RESULTS = PROJECT_ROOT / "eval" / "results" / "guardrail_results.csv"
REPORT = PROJECT_ROOT / "reports" / "guardrails_report.md"
BOOTSTRAP_SAMPLES = 2000
REPEATS = 3  # the LLM self-check is not fully deterministic, so input rails run several times


def read_jsonl(path) -> list[dict]:  # noqa: ANN001
    """Rows of a JSON-lines file."""
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def rate_ci(flags: list[bool], seed: int) -> tuple[float, float, float]:
    """Rate of True values with a 95% percentile bootstrap interval.

    A bootstrap can't vary when every value is the same, so for 0 or n events the
    rule of three (3/n) gives the open end of the interval instead.
    """
    n = len(flags)
    hits = sum(flags)
    if hits == 0:
        return 0.0, 0.0, min(1.0, 3 / n)
    if hits == n:
        return 1.0, max(0.0, 1 - 3 / n), 1.0
    rng = random.Random(seed)
    stats = sorted(sum(flags[rng.randrange(n)] for _ in range(n)) / n for _ in range(BOOTSTRAP_SAMPLES))
    return sum(flags) / n, stats[int(0.025 * BOOTSTRAP_SAMPLES)], stats[int(0.975 * BOOTSTRAP_SAMPLES) - 1]


def main() -> int:
    """Run every check and write the CSV and the report."""
    logging.basicConfig(level=logging.WARNING)
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    settings = get_settings()
    redactor = query_redactor(settings)
    guard = Guard(settings, redactor)

    rows: list[dict] = []
    for run in range(1, REPEATS + 1):
        for item in read_jsonl(ATTACKS):
            # The pipeline redacts the question before the rails see it, so the evaluation does too.
            result = guard.check_input(redactor.redact(item["prompt"]).text)
            rows.append({"kind": "input", "run": run, "id": item["id"], "category": item["category"],
                         "expected": item["expected"], "blocked": result.blocked, "rail": result.rail or "",
                         "latency_ms": round(result.latency_ms, 1), "text": item["prompt"]})  # fmt: skip
        print(f"input run {run} done")
    for item in read_jsonl(OUTPUT_CHECKS):
        result = guard.check_output("question", item["answer"])
        rows.append({"kind": "output", "run": 1, "id": item["id"], "category": "output", "expected": item["expected"],
                     "blocked": result.blocked, "rail": result.rail or "", "latency_ms": round(result.latency_ms, 1),
                     "text": item["answer"]})  # fmt: skip

    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    with RESULTS.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    poisoned = read_jsonl(POISONED)
    corpus = [json.loads(line) for line in settings.paths.chunks_file.read_text(encoding="utf-8").splitlines()]
    REPORT.write_text(render(rows, poisoned, corpus, settings), encoding="utf-8", newline="\n")
    print(f"wrote {RESULTS} and {REPORT}")
    return 0


def render(rows: list[dict], poisoned: list[dict], corpus: list[dict], settings) -> str:  # noqa: ANN001
    """Markdown report computed from the result rows."""
    seed = settings.router.seed
    all_inputs = [r for r in rows if r["kind"] == "input"]
    inputs = [r for r in all_inputs if r["run"] == 1]
    harmful = [r for r in inputs if r["expected"] == "block"]
    harmless = [r for r in inputs if r["expected"] == "allow"]
    block_rate, b_lo, b_hi = rate_ci([r["blocked"] for r in harmful], seed)
    fp_rate, f_lo, f_hi = rate_ci([r["blocked"] for r in harmless], seed)
    lines = [
        "# Guardrails report",
        "",
        f"Generated by `python -m scripts.eval_guardrails` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} from "
        "`eval/results/guardrail_results.csv`. NeMo Guardrails 0.24.1; the LLM self-check runs on "
        f"`{settings.llm.small_model}`. Prompts are redacted before the rails see them, as in the pipeline.",
        "",
        "## Input rails (`eval/attacks.jsonl`)",
        "",
        f"The input rails ran {REPEATS} times over the same prompts. The tables below use run 1; the run-to-run "
        "comparison follows them.",
        "",
        "| Metric | Value | 95% CI (bootstrap; rule of three at 0 or n) | n |",
        "|---|---|---|---|",
        f"| Block rate on prompts that should be blocked | {block_rate:.3f} | {b_lo:.3f}–{b_hi:.3f} | {len(harmful)} |",
        f"| False-positive rate on harmless prompts | {fp_rate:.3f} | {f_lo:.3f}–{f_hi:.3f} | {len(harmless)} |",
        "",
        "| Category | Expected | Blocked | n |",
        "|---|---|---|---|",
    ]
    for category in sorted({r["category"] for r in inputs}):
        part = [r for r in inputs if r["category"] == category]
        lines.append(f"| {category} | {part[0]['expected']} | {sum(r['blocked'] for r in part)} | {len(part)} |")
    by_rail = Counter(r["rail"] for r in inputs if r["blocked"])
    latencies = [r["latency_ms"] for r in inputs]
    lines += [
        "",
        "Which rail blocked (all input prompts): " + ", ".join(f"`{rail}` {n}" for rail, n in by_rail.most_common()) + ".",
        f"Input-rail latency: median {statistics.median(latencies):.0f} ms, max {max(latencies):.0f} ms "
        "(pattern rails take a few ms; the LLM self-check makes one API call).",
        "",
    ]
    lines += ["| Run | Block rate (harmful) | False-positive rate (harmless) |", "|---|---|---|"]
    per_run = []
    for run in range(1, REPEATS + 1):
        part = [r for r in all_inputs if r["run"] == run]
        b = sum(r["blocked"] for r in part if r["expected"] == "block") / len(harmful)
        f = sum(r["blocked"] for r in part if r["expected"] == "allow") / len(harmless)
        per_run.append((b, f))
        lines.append(f"| {run} | {b:.3f} | {f:.3f} |")
    lines.append(
        f"| mean | {statistics.mean(b for b, _ in per_run):.3f} | {statistics.mean(f for _, f in per_run):.3f} |"
    )
    outcomes: dict[str, set[bool]] = {}
    for r in all_inputs:
        outcomes.setdefault(r["id"], set()).add(r["blocked"])
    unstable = sorted(prompt_id for prompt_id, seen in outcomes.items() if len(seen) > 1)
    lines += ["", f"Prompts whose outcome changed between runs: {', '.join(f'`{u}`' for u in unstable) or 'none'}.", ""]
    misses = [r for r in harmful if not r["blocked"]]
    false_pos = [r for r in harmless if r["blocked"]]
    for title, part in (("Harmful prompts that got through", misses), ("Harmless prompts that were blocked", false_pos)):
        lines += [f"### {title}: {len(part)}", ""]
        lines += [f"- `{r['id']}` ({r['category']}{', ' + r['rail'] if r['rail'] else ''}): {r['text']}" for r in part]
        lines.append("")

    outputs = [r for r in rows if r["kind"] == "output"]
    leaks = [r for r in outputs if r["expected"] == "block"]
    clean = [r for r in outputs if r["expected"] == "allow"]
    lines += [
        "## Output rail (`eval/output_checks.jsonl`)",
        "",
        f"- Answers containing identifiers blocked: {sum(r['blocked'] for r in leaks)} of {len(leaks)}",
        f"- Clean answers allowed: {sum(not r['blocked'] for r in clean)} of {len(clean)}",
        "",
        "## Injection hidden in documents",
        "",
    ]
    flagged = [c for c in poisoned if injection_matches(c["text"])]
    truly_poisoned = [c for c in poisoned if c["poisoned"]]
    caught = [c for c in truly_poisoned if injection_matches(c["text"])]
    false_flags = [c for c in poisoned if not c["poisoned"] and injection_matches(c["text"])]
    corpus_flagged = [c for c in corpus if c.get("injection_flags")]
    lines += [
        f"- Poisoned fixture (`tests/fixtures/poisoned_chunks.jsonl`): {len(caught)} of {len(truly_poisoned)} "
        f"poisoned chunks flagged, {len(false_flags)} of {len(poisoned) - len(truly_poisoned)} clean chunks flagged "
        f"({len(flagged)} flagged in total). Flagged chunks are dropped from the context before generation.",
        f"- Real corpus (`chunks.jsonl`): {len(corpus_flagged)} of {len(corpus)} chunks flagged at ingestion.",
    ]
    for c in corpus_flagged[:10]:
        lines.append(f"  - `{c['chunk_id']}` ({c['source']}, {c['section'][:40]}): {', '.join(c['injection_flags'])}")
    lines += [
        "",
        f"With n = {len(harmful)} harmful and {len(harmless)} harmless prompts, the intervals are wide; "
        "treat the rates as indicative.",
    ]
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    sys.exit(main())
